SELECT DISTINCT
    d.id AS dashboard_id,
    d.pagename AS dashboard_name,
    d.username AS dashboard_owner,
    rf.ID AS rich_filter_id,
    rf.NAME AS rich_filter_name,
    jf.id AS jira_filter_id,
    jf.filtername AS jira_filter_name,
    jf.reqcontent AS jira_filter_jql
FROM portalpage d
JOIN portletconfiguration g ON d.id = g.portalpage
JOIN gadgetuserpreference p ON g.id = p.portletconfiguration
JOIN `AO_24D977_QRFRFE0` rf ON rf.ID = CAST(p.userprefvalue AS SIGNED)
INNER JOIN searchrequest jf ON rf.JIRA_FILTER_ID = jf.id
WHERE p.userprefkey = 'rf'
  AND (
