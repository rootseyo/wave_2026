try {
    sql.eachRow(query) { row ->
        def pname = '"' + (row.project_name ?: '').toString().replace('"', '""') + '"'
        def pkey = '"' + (row.pkey ?: '').toString().replace('"', '""') + '"'
        def issueCount = row.issue_count ?: 0
        def sizeMb = row.total_attachment_size_mb ?: 0
        def sizeGb = row.total_attachment_size_gb ?: 0
        csv.append("${pname},${pkey},${issueCount},${sizeMb},${sizeGb}\r\n")
    }
} finally {
    sql.close()
    conn.close()
}

