-- JEditor template file-reference investigation
-- Database: MySQL
-- Read-only test queries only.
-- Target files: t1.html, t2.html, t3.html

-- 1) Check whether the JEditor app is installed/enabled.
SELECT *
FROM pluginstate
WHERE pluginkey = 'com.jiraeditor.jeditor';

-- 2) Search Jira property tables for the template file names.
SELECT
    'propertystring' AS source_table,
    pe.entity_name,
    pe.entity_id,
    pe.property_key,
    ps.propertyvalue AS matched_value
FROM propertyentry pe
JOIN propertystring ps
  ON ps.id = pe.id
WHERE ps.propertyvalue REGEXP 't1\\.html|t2\\.html|t3\\.html'

UNION ALL

SELECT
    'propertytext' AS source_table,
    pe.entity_name,
    pe.entity_id,
    pe.property_key,
    pt.propertyvalue AS matched_value
FROM propertyentry pe
JOIN propertytext pt
  ON pt.id = pe.id
WHERE pt.propertyvalue REGEXP 't1\\.html|t2\\.html|t3\\.html';

-- 3) Find all text-like columns in Jira/AO tables that can contain filenames.
-- Execute the SQL statements generated by this query in a separate step.
SELECT CONCAT(
    'SELECT ''', TABLE_NAME, ''' AS table_name, ''',
    COLUMN_NAME, ''' AS column_name, `',
    COLUMN_NAME, '` AS matched_value FROM `',
    TABLE_NAME,
    '` WHERE `', COLUMN_NAME,
    '` REGEXP ''t1\\\\.html|t2\\\\.html|t3\\\\.html'';'
) AS generated_search_sql
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND DATA_TYPE IN ('char', 'varchar', 'text', 'tinytext', 'mediumtext', 'longtext')
ORDER BY TABLE_NAME, ORDINAL_POSITION;

-- 4) Limit the candidate list to AO tables and columns related to templates,
-- projects, schemes, settings, content, or filenames.
SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    CHARACTER_MAXIMUM_LENGTH
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME LIKE 'AO_%'
  AND DATA_TYPE IN ('char', 'varchar', 'text', 'tinytext', 'mediumtext', 'longtext')
  AND (
       UPPER(COLUMN_NAME) LIKE '%TEMPLATE%'
    OR UPPER(COLUMN_NAME) LIKE '%PROJECT%'
    OR UPPER(COLUMN_NAME) LIKE '%SCHEME%'
    OR UPPER(COLUMN_NAME) LIKE '%SETTING%'
    OR UPPER(COLUMN_NAME) LIKE '%CONTENT%'
    OR UPPER(COLUMN_NAME) LIKE '%BODY%'
    OR UPPER(COLUMN_NAME) LIKE '%FILE%'
    OR UPPER(COLUMN_NAME) LIKE '%NAME%'
  )
ORDER BY TABLE_NAME, ORDINAL_POSITION;

-- 5) Generate focused searches only for the candidate AO columns above.
-- Execute the generated statements after reviewing them.
SELECT CONCAT(
    'SELECT ''', TABLE_NAME, ''' AS table_name, ''',
    COLUMN_NAME, ''' AS column_name, `',
    COLUMN_NAME, '` AS matched_value FROM `',
    TABLE_NAME,
    '` WHERE `', COLUMN_NAME,
    '` REGEXP ''t1\\\\.html|t2\\\\.html|t3\\\\.html'';'
) AS generated_candidate_search_sql
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME LIKE 'AO_%'
  AND DATA_TYPE IN ('char', 'varchar', 'text', 'tinytext', 'mediumtext', 'longtext')
  AND (
       UPPER(COLUMN_NAME) LIKE '%TEMPLATE%'
    OR UPPER(COLUMN_NAME) LIKE '%PROJECT%'
    OR UPPER(COLUMN_NAME) LIKE '%SCHEME%'
    OR UPPER(COLUMN_NAME) LIKE '%SETTING%'
    OR UPPER(COLUMN_NAME) LIKE '%CONTENT%'
    OR UPPER(COLUMN_NAME) LIKE '%BODY%'
    OR UPPER(COLUMN_NAME) LIKE '%FILE%'
    OR UPPER(COLUMN_NAME) LIKE '%NAME%'
  )
ORDER BY TABLE_NAME, ORDINAL_POSITION;

-- 6) Check Jira's shared-home references if the DB result contains a path or
-- property key. This is only a reference query; actual file inspection must
-- be done on Jira shared home.
SELECT
    pe.entity_name,
    pe.entity_id,
    pe.property_key,
    COALESCE(ps.propertyvalue, pt.propertyvalue) AS property_value
FROM propertyentry pe
LEFT JOIN propertystring ps ON ps.id = pe.id
LEFT JOIN propertytext pt ON pt.id = pe.id
WHERE LOWER(CONCAT_WS(
    ' ', pe.entity_name, pe.property_key,
    ps.propertyvalue, pt.propertyvalue
)) REGEXP 'jeditor|template|html|shared.home|file';

