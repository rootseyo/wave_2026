SELECT
    p.pkey AS project_key,
    p.pname AS project_name,
    pt.ID AS template_id,
    pt.NAME AS template_name,
    COALESCE(pt.DESCRIPTION, '') AS description,
    COALESCE(pt.PREPOPULATION_FIELDS, '') AS field_id,
    CASE
        WHEN pt.PREPOPULATION_FIELDS IS NULL OR pt.PREPOPULATION_FIELDS IN ('', 'EMPTY_VALUE') THEN ''
        WHEN pt.PREPOPULATION_FIELDS = 'description' THEN 'Description'
        WHEN pt.PREPOPULATION_FIELDS = 'environment' THEN 'Environment'
        WHEN cf.cfname IS NOT NULL THEN CONCAT(pt.PREPOPULATION_FIELDS, '(', cf.cfname, ')')
        ELSE COALESCE(
            (
                SELECT GROUP_CONCAT(CONCAT('customfield_', cf2.id, '(', cf2.cfname, ')') ORDER BY cf2.id SEPARATOR ', ')
                FROM customfield cf2
                WHERE FIND_IN_SET(CONCAT('customfield_', cf2.id), REPLACE(pt.PREPOPULATION_FIELDS, ' ', '')) > 0
                   OR FIND_IN_SET(cf2.id, REPLACE(pt.PREPOPULATION_FIELDS, ' ', '')) > 0
            ),
            pt.PREPOPULATION_FIELDS
        )
    END AS field_name,
    COALESCE(cf.cfname, '') AS custom_field_name,
    CASE
        WHEN pt.PREPOPULATION_TYPES IS NULL OR pt.PREPOPULATION_TYPES IN ('', 'EMPTY_VALUE') THEN ''
        ELSE COALESCE(
            (
                SELECT GROUP_CONCAT(CONCAT(it.id, '(', it.pname, ')') ORDER BY it.id SEPARATOR ', ')
                FROM issuetype it
                WHERE FIND_IN_SET(it.id, REPLACE(pt.PREPOPULATION_TYPES, ' ', '')) > 0
            ),
            pt.PREPOPULATION_TYPES
        )
    END AS issue_types,
    COALESCE(pt.PREPOPULATION_TYPES, '') AS issue_types_raw,
    CASE
        WHEN pt.PREPOPULATION_FIELDS IS NOT NULL
         AND pt.PREPOPULATION_FIELDS NOT IN ('', 'EMPTY_VALUE')
         AND pt.PREPOPULATION_TYPES IS NOT NULL
         AND pt.PREPOPULATION_TYPES NOT IN ('', 'EMPTY_VALUE')
        THEN 'YES'
        ELSE 'NO'
    END AS autofill_enabled,
    COALESCE(pt.SHARED, 0) AS is_shared,
    COALESCE(pt.VISIBILITY_FIELDS, '') AS visibility_fields,
    COALESCE(pt.VISIBILITY_TYPES, '') AS visibility_types,
    COALESCE(pt.VISIBILITY_USER_GROUPS, '') AS visibility_groups,
    pt.BODY AS content
FROM project p
JOIN ao_bf4748_project_template pt ON pt.PROJECT_ID = p.id
LEFT JOIN customfield cf ON pt.PREPOPULATION_FIELDS = CONCAT('customfield_', cf.id)
